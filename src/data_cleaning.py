"""
Data cleaning pipeline for the Tetouan City power-consumption dataset.

Dataset: "Power Consumption of Tetouan City" (UCI Machine Learning Repository,
dataset 849). 52,416 rows at 10-minute resolution, 2017-01-01 00:00 to
2017-12-30 23:50. Three urban electricity distribution networks in Tetouan,
northern Morocco (Quads / Smir / Boussafou substations, operated by Amendis),
labelled Zone 1 / Zone 2 / Zone 3, plus five weather channels.
Source paper: Salam, A. & El Hibaoui, A. (2018), "Comparison of Machine Learning
Algorithms for the Power Consumption Prediction", IEEE IRSEC.

Provenance note: this project was originally started from a modified copy of
this dataset in which the three zones had been renamed to college-block labels,
the year relabelled to 2023 (2017 and 2023 share an identical weekday calendar),
~9% of the timestamp strings were corrupted by a bad export (minutes written as
a running counter, e.g. "0:60", "0:2591"), and ~150 power values (0.1% of cells,
magnitude < 0.05%) were altered. The pipeline was reverted to the pristine UCI
original; those differences are far below the precision of any reported metric.

Run: python src/data_cleaning.py
"""

import pandas as pd
from pathlib import Path

RAW_PATH = Path("data/raw/Tetuan City power consumption (UCI original).csv")
PROCESSED_PATH = Path("data/processed/cleaned_energy_data.csv")
REPORT_PATH = Path("reports/01_data_cleaning_report.md")

# UCI column name -> project column name
RENAME = {
    "DateTime": "Datetime",
    "Wind Speed": "WindSpeed",
    "general diffuse flows": "GeneralDiffuseFlows",
    "diffuse flows": "DiffuseFlows",
    "Zone 1 Power Consumption": "PowerConsumption_Zone1",
    "Zone 2  Power Consumption": "PowerConsumption_Zone2",
    "Zone 3  Power Consumption": "PowerConsumption_Zone3",
}
WEATHER_COLS = ["Temperature", "Humidity", "WindSpeed", "GeneralDiffuseFlows", "DiffuseFlows"]
POWER_COLS = ["PowerConsumption_Zone1", "PowerConsumption_Zone2", "PowerConsumption_Zone3"]


def clean() -> tuple[pd.DataFrame, dict]:
    df = pd.read_csv(RAW_PATH)
    # tolerate single/double spaces in the raw Zone headers
    df.columns = [c.replace("  ", " ") for c in df.columns]
    rename = {k.replace("  ", " "): v for k, v in RENAME.items()}
    df = df.rename(columns=rename)

    stats = {"rows_raw": len(df), "cols_raw": df.shape[1]}

    # --- Timestamps: parse the genuine 10-minute sequence ---
    df["Datetime"] = pd.to_datetime(df["Datetime"], format="%m/%d/%Y %H:%M")
    expected = pd.date_range(df["Datetime"].min(), df["Datetime"].max(), freq="10min")
    stats["timestamp_regular"] = bool(len(expected) == len(df) and (df["Datetime"].values == expected.values).all())

    # --- Structural checks ---
    stats["duplicate_rows"] = int(df.duplicated().sum())
    stats["duplicate_timestamps"] = int(df["Datetime"].duplicated().sum())
    stats["missing_values"] = int(df.isna().sum().sum())

    numeric_cols = WEATHER_COLS + POWER_COLS
    stats["negative_values"] = {c: int((df[c] < 0).sum()) for c in numeric_cols}
    stats["zero_values"] = {c: int((df[c] == 0).sum()) for c in numeric_cols}

    # --- Flag (do not drop) IQR outliers in power columns ---
    stats["iqr_outliers"] = {}
    for c in POWER_COLS:
        q1, q3 = df[c].quantile(0.25), df[c].quantile(0.75)
        iqr = q3 - q1
        lo, hi = q1 - 1.5 * iqr, q3 + 1.5 * iqr
        flag_col = f"{c}_outlier"
        df[flag_col] = ~df[c].between(lo, hi)
        stats["iqr_outliers"][c] = {
            "count": int(df[flag_col].sum()),
            "pct": round(100 * df[flag_col].mean(), 2),
            "bounds": (round(lo, 1), round(hi, 1)),
        }

    df = df.sort_values("Datetime").reset_index(drop=True)
    df = df[["Datetime"] + WEATHER_COLS + POWER_COLS + [f"{c}_outlier" for c in POWER_COLS]]
    stats["rows_clean"] = len(df)
    stats["date_range"] = (str(df["Datetime"].min()), str(df["Datetime"].max()))

    return df, stats


def write_report(stats: dict) -> None:
    lines = [
        "# Data Cleaning Report",
        "",
        f"Generated by `src/data_cleaning.py` from `{RAW_PATH.name}`.",
        "",
        "## Dataset",
        "**Power Consumption of Tetouan City**: UCI Machine Learning Repository (dataset 849). "
        "Three urban electricity distribution networks in Tetouan, northern Morocco "
        "(Quads / Smir / Boussafou substations, operator Amendis), recorded every 10 minutes "
        "through 2017, with five weather channels. Zones are labelled Zone 1 / Zone 2 / Zone 3. "
        "Source paper: Salam & El Hibaoui (2018), IEEE IRSEC.",
        "",
        "## Provenance note",
        "This project began from a modified copy of the dataset: the three zones had been renamed "
        "to college-block labels, the year relabelled 2017 -> 2023 (the two years share an identical "
        "weekday calendar), ~9% of timestamp strings were corrupted by a faulty export (minutes as a "
        "running counter, e.g. `0:60`, `0:2591`), and ~150 power values (0.1% of cells, magnitude "
        "< 0.05%) were altered. The pipeline now reads the pristine UCI original, and all models "
        "and metrics reported elsewhere in this project were refitted on this cleaned output. "
        "See `reports/05_modeling_report.md` for the separate modelling defects found in the same "
        "audit and the corrected results.",
        "",
        "## Summary",
        f"- Raw rows: {stats['rows_raw']:,} | Clean rows: {stats['rows_clean']:,}",
        f"- Date range: {stats['date_range'][0]} to {stats['date_range'][1]} (10-min intervals)",
        f"- Timestamps form a complete gap-free 10-minute sequence: {stats['timestamp_regular']}",
        f"- Duplicate rows: {stats['duplicate_rows']} | Duplicate timestamps: {stats['duplicate_timestamps']}",
        f"- Missing values (any column): {stats['missing_values']}",
        "",
        "## Negative / zero values (physically invalid if present)",
    ]
    for c in WEATHER_COLS + POWER_COLS:
        lines.append(f"- {c}: negative={stats['negative_values'][c]}, zero={stats['zero_values'][c]}")

    lines += ["", "## IQR outliers in power columns (flagged only, not removed: pending EDA review)"]
    for c, info in stats["iqr_outliers"].items():
        lines.append(f"- {c}: {info['count']} rows ({info['pct']}%), bounds={info['bounds']}")

    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    df, stats = clean()
    PROCESSED_PATH.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(PROCESSED_PATH, index=False)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    write_report(stats)
    print(f"Saved cleaned data -> {PROCESSED_PATH} ({len(df):,} rows)")
    print(f"Saved report -> {REPORT_PATH}")
